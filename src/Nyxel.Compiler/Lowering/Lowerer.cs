using System.Globalization;
using System.Text;
using Nyxel.Compiler.Binding;
using Nyxel.Compiler.Symbols;
using Nyxel.Compiler.Syntax;
using Nyxel.Compiler.Text;
using CSharpFacts = Microsoft.CodeAnalysis.CSharp.SyntaxFacts;
using CSharpLiteral = Microsoft.CodeAnalysis.CSharp.SymbolDisplay;

namespace Nyxel.Compiler.Lowering;

/// <summary>
/// Lowering (docs/design/lowering.md): the bound program as C# source. Every Nyxel statement is one C# line with a
/// <c>#line</c> span directive back to it (docs/design/debug-mapping.md); types are written in full with
/// <c>global::</c>, so C#'s name lookup has nothing to decide. <paramref name="referencesHave"/> tells whether the
/// referenced assemblies have a type, by its metadata name.
/// </summary>
internal sealed partial class Lowerer(BoundProgram program, Func<string, bool> referencesHave)
{
    private readonly CSharpWriter _writer = new();
    private SourceText _source = null!;
    private int _temporaries;
    private Dictionary<LocalSymbol, string> _localNames = [];

    // How 'self' is written: 'this', or the receiver of an enum's extension block.
    private string _self = "this";

    public static string Lower(BoundProgram program, Func<string, bool> referencesHave) => new Lowerer(program, referencesHave).LowerProgram();

    private string LowerProgram()
    {
        _writer.WriteRaw("// <auto-generated>Generated by the Nyxel compiler from .nyxel files.</auto-generated>");
        _writer.WriteRaw("#nullable disable");
        _writer.WriteRaw("#pragma warning disable");
        foreach (var group in program.Types.GroupBy(t => t.ContainingNamespace))
        {
            var ns = group.Key;
            if (!ns.IsGlobal)
            {
                _writer.WriteHidden($"namespace {string.Join(".", ns.FullName.Split('.').Select(Escape))}");
                _writer.WriteHidden("{");
                _writer.Indent();
            }
            foreach (var type in group)
            {
                LowerType(type);
            }
            if (!ns.IsGlobal)
            {
                _writer.Unindent();
                _writer.WriteHidden("}");
            }
        }
        DeclareMissingAttributes();
        return _writer.ToString();
    }

    private void LowerType(SourceNamedTypeSymbol type)
    {
        _source = type.SyntaxTree.Text;
        _self = "this";
        if (type.TypeKind == TypeKind.Enum)
        {
            LowerEnum(type);
            return;
        }
        if (type.IsDataEnum)
        {
            LowerDataEnum(type);
            return;
        }
        var access = type.Accessibility == Accessibility.Public ? "public" : "internal";
        var keyword = type.TypeKind == TypeKind.Struct ? "struct" : "class";
        _writer.WriteHidden($"{access} {keyword} {Escape(type.Name)}");
        _writer.WriteHidden("{");
        _writer.Indent();
        LowerMembers(type);
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    private void LowerMembers(SourceNamedTypeSymbol type)
    {
        foreach (var member in type.GetMembers())
        {
            switch (member)
            {
                case SourceFieldSymbol field:
                    LowerField(field);
                    break;
                case SourcePropertySymbol property:
                    LowerProperty(property);
                    break;
                case SourceMethodSymbol { Syntax: not null } method:
                    LowerMethod(type, method);
                    break;
                case SourceMethodSymbol { MethodKind: MethodKind.Constructor } when type.TypeKind == TypeKind.Struct:
                    // The implicit init (ADR-0013). C# runs a struct's field initializers only in a constructor that
                    // is written out, and requires one when there are initializers (CS8983).
                    _writer.WriteHidden($"public {Escape(type.Name)}() {{ }}");
                    break;
            }
        }
    }

    /// <summary>
    /// A <c>struct enum</c> or <c>class enum</c> (ADR-0046). Each case is a nested record type with its data as
    /// get-only properties, a constructor whose parameters are the data in camelCase (ADR-0024), <c>Deconstruct</c> and
    /// a <c>ToString</c> written like creating it in Nyxel: <c>Burn(Amount = 12, Seconds = 3)</c>. The enum's own
    /// members are on the outer type.
    /// <list type="bullet">
    /// <item>A <c>class enum</c> is C# 15's closed hierarchy of records: the abstract base can't be derived from in other
    /// assemblies, and C# 15's <c>switch</c> knows when it lists every case. Each case is a sealed record class; a case
    /// without data is one shared object, in an internal static field of the base.</item>
    /// <item>A <c>struct enum</c> is a union struct of C# 15 written out: a tag (the case's ordinal, so that all zeros
    /// is the first case) and the data of every case in private fields, those of one type shared between cases. A
    /// constructor per case, <c>Value</c> and <c>HasValue</c> (<c>IUnion</c>) and a <c>TryGetValue</c> per case
    /// let C# 15 switch on it without boxing. It is a readonly record struct, so its equality compares the tag and
    /// the fields: the same case with equal data, the fields a case doesn't use staying zero.</item>
    /// </list>
    /// </summary>
    private void LowerDataEnum(SourceNamedTypeSymbol type)
    {
        var access = type.Accessibility == Accessibility.Public ? "public" : "internal";
        var cases = type.Cases.ToList();
        var name = TypeName(type);
        if (type.TypeKind == TypeKind.Class)
        {
            _writer.WriteHidden($"{access} closed record class {Escape(type.Name)}");
            _writer.WriteHidden("{");
            _writer.Indent();
            foreach (var @case in cases)
            {
                LowerCaseType(@case, $"sealed record class {Escape(@case.Name)} : {name}");
            }
            foreach (var @case in cases.Where(c => !c.HasData))
            {
                _writer.WriteHidden($"internal static readonly {CaseTypeName(@case)} {SharedCaseField(@case)} = new {CaseTypeName(@case)}();");
            }
            LowerMembers(type);
            _writer.Unindent();
            _writer.WriteHidden("}");
            return;
        }

        _writer.WriteHidden("[global::System.Runtime.CompilerServices.Union]");
        _writer.WriteHidden($"{access} readonly record struct {Escape(type.Name)} : global::System.Runtime.CompilerServices.IUnion");
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var @case in cases)
        {
            LowerCaseType(@case, $"readonly record struct {Escape(@case.Name)}");
        }

        // The data of the cases in fields of their types, a case using each field at most once.
        var slotTypes = new List<string>();
        var slotOf = new Dictionary<ParameterSymbol, int>(ReferenceEqualityComparer.Instance);
        foreach (var @case in cases)
        {
            var used = new HashSet<int>();
            foreach (var item in @case.Items)
            {
                var itemType = TypeName(item.Type);
                var slot = Enumerable.Range(0, slotTypes.Count).FirstOrDefault(i => !used.Contains(i) && slotTypes[i] == itemType, -1);
                if (slot < 0)
                {
                    slot = slotTypes.Count;
                    slotTypes.Add(itemType);
                }
                used.Add(slot);
                slotOf.Add(item, slot);
            }
        }
        var tagType = cases.Count <= byte.MaxValue + 1 ? "byte" : "int";
        _writer.WriteHidden($"internal readonly {tagType} {StructEnumTag};");
        for (var slot = 0; slot < slotTypes.Count; slot++)
        {
            _writer.WriteHidden($"private readonly {slotTypes[slot]} {Slot(slot)};");
        }

        foreach (var @case in cases)
        {
            var sets = @case.Items.Select(i => $" this.{Slot(slotOf[i])} = value.{Escape(i.Name)};");
            _writer.WriteHidden($"public {Escape(type.Name)}({CaseTypeName(@case)} value) {{ this.{StructEnumTag} = {@case.Ordinal};{string.Concat(sets)} }}");
        }
        string Read(SourceEnumCaseSymbol @case) =>
            $"new {CaseTypeName(@case)}({string.Join(", ", @case.Items.Select(i => $"this.{Slot(slotOf[i])}"))})";
        var values = string.Concat(cases.Select(c => $"{c.Ordinal} => {Read(c)}, "));
        _writer.WriteHidden($"public object Value => this.{StructEnumTag} switch {{ {values}_ => null }};");
        _writer.WriteHidden("public bool HasValue => true;");
        foreach (var @case in cases)
        {
            var isCase = $"this.{StructEnumTag} == {@case.Ordinal}";
            var value = @case.HasData ? $"{isCase} ? {Read(@case)} : default" : "default";
            _writer.WriteHidden($"public bool TryGetValue(out {CaseTypeName(@case)} value) {{ value = {value}; return {isCase}; }}");
        }
        var texts = string.Concat(cases.Select(c => $"{c.Ordinal} => {CaseText(c, i => $"this.{Slot(slotOf[i])}")}, "));
        _writer.WriteHidden($"public override string ToString() => this.{StructEnumTag} switch {{ {texts}_ => \"\" }};");
        _writer.WriteHidden($"internal static bool {StructEnumIs}({name}? value, int tag) => value.HasValue && value.GetValueOrDefault().{StructEnumTag} == tag;");
        LowerMembers(type);
        _writer.Unindent();
        _writer.WriteHidden("}");

        static string Slot(int slot) => $"__nyxel_{slot}";
    }

    /// <summary>The tag of a <c>struct enum</c>: the ordinal of its case. <c>is</c> reads it (internal to the assembly).</summary>
    private const string StructEnumTag = "__nyxel_Tag";

    /// <summary>The helper of a <c>struct enum</c> that tells the case of an <c>E?</c> (and of an object, through <c>as E?</c>).</summary>
    private const string StructEnumIs = "__nyxel_Is";

    /// <summary>A case as a nested record type: the data, the constructor, <c>Deconstruct</c> and <c>ToString</c>.</summary>
    private void LowerCaseType(SourceEnumCaseSymbol @case, string header)
    {
        _writer.WriteMapped(_source, @case.Syntax.Span, $"public {header}");
        _writer.WriteHidden("{");
        _writer.Indent();
        var items = @case.Items;
        if (items.Length > 0)
        {
            var parameters = string.Join(", ", items.Select(i => $"{TypeName(i.Type)} {CaseParameter(i)}"));
            var sets = string.Concat(items.Select(i => $" this.{Escape(i.Name)} = {CaseParameter(i)};"));
            _writer.WriteHidden($"public {Escape(@case.Name)}({parameters}) {{{sets} }}");
            foreach (var item in items)
            {
                _writer.WriteHidden($"public {TypeName(item.Type)} {Escape(item.Name)} {{ get; }}");
            }
            var outs = string.Join(", ", items.Select(i => $"out {TypeName(i.Type)} {CaseParameter(i)}"));
            var gets = string.Concat(items.Select(i => $" {CaseParameter(i)} = this.{Escape(i.Name)};"));
            _writer.WriteHidden($"public void Deconstruct({outs}) {{{gets} }}");
        }
        _writer.WriteHidden($"public override string ToString() => {CaseText(@case, i => $"this.{Escape(i.Name)}")};");
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    /// <summary>A case as text (ADR-0046): <c>"Idle"</c>, or <c>$"Burn(Amount = {...}, Seconds = {...})"</c> with each item read by <paramref name="read"/>.</summary>
    private static string CaseText(SourceEnumCaseSymbol @case, Func<ParameterSymbol, string> read)
    {
        if (@case.Items.Length == 0)
        {
            return CSharpLiteral.FormatLiteral(@case.Name, quote: true);
        }
        var parts = @case.Items.Select(i => $"{Interpolated(i.Name)} = {{({read(i)})}}");
        return $"$\"{Interpolated(@case.Name)}({string.Join(", ", parts)})\"";

        static string Interpolated(string text) =>
            CSharpLiteral.FormatLiteral(text, quote: false).Replace("{", "{{", StringComparison.Ordinal).Replace("}", "}}", StringComparison.Ordinal);
    }

    /// <summary>A case's data as a parameter of its constructor: camelCase (ADR-0024).</summary>
    private static string CaseParameter(ParameterSymbol item) => Escape(Naming.CamelCase(item.Name));

    /// <summary>The nested type of a case: <c>global::Game.AiState.Chasing</c>.</summary>
    private static string CaseTypeName(SourceEnumCaseSymbol @case) => $"{TypeName(@case.ContainingType)}.{Escape(@case.Name)}";

    /// <summary>The field of a <c>class enum</c> that holds the one object of a case without data.</summary>
    private static string SharedCaseField(SourceEnumCaseSymbol @case) => $"__nyxel_{@case.Name}";

    /// <summary>
    /// The attributes C# 15's unions and closed classes need (ADR-0047): .NET 10 doesn't have them, so the generated
    /// assembly declares its own, internal, when its program uses them and the references lack them.
    /// </summary>
    private void DeclareMissingAttributes()
    {
        var dataEnums = program.Types.Where(t => t.IsDataEnum).ToList();
        var declarations = new List<string>();
        if (dataEnums.Any(t => t.TypeKind == TypeKind.Struct))
        {
            if (!referencesHave("System.Runtime.CompilerServices.UnionAttribute"))
            {
                declarations.Add("[global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct, AllowMultiple = false)]");
                declarations.Add("internal sealed class UnionAttribute : global::System.Attribute { }");
            }
            if (!referencesHave("System.Runtime.CompilerServices.IUnion"))
            {
                declarations.Add("internal interface IUnion { object Value { get; } }");
            }
        }
        if (dataEnums.Any(t => t.TypeKind == TypeKind.Class) && !referencesHave("System.Runtime.CompilerServices.IsClosedTypeAttribute"))
        {
            declarations.Add("[global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false)]");
            declarations.Add("internal sealed class IsClosedTypeAttribute : global::System.Attribute { }");
        }
        if (declarations.Count == 0)
        {
            return;
        }
        _writer.WriteHidden("namespace System.Runtime.CompilerServices");
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var declaration in declarations)
        {
            _writer.WriteHidden(declaration);
        }
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    /// <summary>
    /// An enum without data is a C# enum (ADR-0024): <c>[Flags]</c> for a flags enum, its underlying type, and every
    /// case with its value written out. Its functions and properties go into the extension blocks of a static class
    /// named after it (ADR-0029), so C# calls them as <c>element.Weakness()</c> and <c>Element.Parse("ice")</c>. Its
    /// <c>static let</c>s are fields of that class, each with an extension property of the same name, so C# reads
    /// <c>Tile.Gate</c>, and <c>TileExtensions.Gate</c> where it needs a constant (ADR-0045).
    /// </summary>
    private void LowerEnum(SourceNamedTypeSymbol type)
    {
        var access = type.Accessibility == Accessibility.Public ? "public" : "internal";
        if (type.IsFlags)
        {
            _writer.WriteHidden("[global::System.Flags]");
        }
        var underlying = type.EnumUnderlyingType is { SpecialType: not Microsoft.CodeAnalysis.SpecialType.System_Int32 } declared ? $" : {TypeName(declared)}" : "";
        _writer.WriteHidden($"{access} enum {Escape(type.Name)}{underlying}");
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var @case in type.Cases)
        {
            _writer.WriteMapped(_source, @case.Syntax.Span, $"{Escape(@case.Name)} = {Literal(@case.ConstantValue).Text},");
        }
        _writer.Unindent();
        _writer.WriteHidden("}");

        var members = type.GetMembers().Where(m => m is SourceMethodSymbol or SourcePropertySymbol).ToList();
        var fields = type.GetMembers().OfType<SourceFieldSymbol>().ToList();
        if (members.Count == 0 && fields.Count == 0)
        {
            return;
        }
        _writer.WriteHidden($"{access} static class {Escape(type.Name)}Extensions");
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var field in fields)
        {
            LowerField(field);
        }
        var shown = fields.Where(f => f.Accessibility != Accessibility.Private).ToList();
        // 'self' is the receiver of the instance block: Nyxel names can't be 'self', so it clashes with nothing.
        _self = "self";
        foreach (var (isStatic, receiver) in new[] { (false, $"{TypeName(type)} self"), (true, TypeName(type)) })
        {
            var block = members.Where(m => m is SourceMethodSymbol method ? method.IsStatic == isStatic : ((SourcePropertySymbol)m).IsStatic == isStatic).ToList();
            if (block.Count == 0 && !(isStatic && shown.Count > 0))
            {
                continue;
            }
            _writer.WriteHidden($"extension({receiver})");
            _writer.WriteHidden("{");
            _writer.Indent();
            if (isStatic)
            {
                foreach (var field in shown)
                {
                    _writer.WriteHidden($"{Modifiers(field.Accessibility, isStatic: true)}{TypeName(field.Type)} {Escape(field.Name)} => {ExtensionsName(type)}.{Escape(field.Name)};");
                }
            }
            foreach (var member in block)
            {
                if (member is SourceMethodSymbol method)
                {
                    LowerMethod(type, method);
                }
                else
                {
                    LowerProperty((SourcePropertySymbol)member);
                }
            }
            _writer.Unindent();
            _writer.WriteHidden("}");
        }
        _self = "this";
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    /// <summary>The static class that holds the extension blocks of a Nyxel enum's members: <c>global::Game.ElementExtensions</c>.</summary>
    private static string ExtensionsName(NamedTypeSymbol enumType) =>
        enumType.ContainingNamespace is { IsGlobal: false } ns
            ? $"global::{string.Join(".", ns.FullName.Split('.').Select(Escape))}.{Escape(enumType.Name)}Extensions"
            : $"global::{Escape(enumType.Name)}Extensions";

    private static bool IsNyxelEnum(NamedTypeSymbol type) => type is SourceNamedTypeSymbol { TypeKind: TypeKind.Enum };

    /// <summary>
    /// A property (ADR-0011): an auto property as C#'s <c>{ get; private set; } = value</c>, a computed one with its
    /// accessors as blocks. A struct's <c>get</c> is <c>readonly</c>, as its <c>self</c> functions are (ADR-0044).
    /// </summary>
    private void LowerProperty(SourcePropertySymbol property)
    {
        var syntax = property.Syntax;
        var modifiers = Modifiers(property.Accessibility, property.IsStatic);
        var name = $"{TypeName(property.Type)} {Escape(property.Name)}";
        if (property.IsAuto)
        {
            var accessors = string.Join(" ", new[] { property.Getter, property.Setter }.OfType<SourceMethodSymbol>()
                .Select(a => $"{AccessorModifiers(property, a)}{(a.MethodKind == MethodKind.PropertyGet ? "get" : "set")};"));
            var initializer = program.Initializers.TryGetValue(property, out var value) ? $" = {Expression(value)};" : "";
            var end = syntax.Initializer?.Span.End ?? syntax.TypeAnnotation.Span.End;
            _writer.WriteMapped(_source, TextSpan.FromBounds(syntax.Span.Start, end), $"{modifiers}{name} {{ {accessors} }}{initializer}");
            return;
        }
        // C# takes 'readonly' on the property when it has only a get (CS8664), on the get otherwise.
        var getterReadOnly = property.Getter is { IsReadOnly: true };
        var wholeReadOnly = getterReadOnly && property.Setter is null;
        _writer.WriteHidden($"{modifiers}{(wholeReadOnly ? "readonly " : "")}{name}");
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var accessor in new[] { property.Getter, property.Setter }.OfType<SourceMethodSymbol>())
        {
            var isGet = accessor.MethodKind == MethodKind.PropertyGet;
            var readOnly = isGet && getterReadOnly && !wholeReadOnly ? "readonly " : "";
            _writer.WriteHidden($"{AccessorModifiers(property, accessor)}{readOnly}{(isGet ? "get" : "set")}");
            LowerBody(accessor);
        }
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    /// <summary>The visibility of an accessor when it narrows its property's (<c>private set</c>).</summary>
    private static string AccessorModifiers(SourcePropertySymbol property, SourceMethodSymbol accessor) =>
        accessor.Accessibility == property.Accessibility ? "" : Modifiers(accessor.Accessibility, isStatic: false);

    private void LowerField(SourceFieldSymbol field)
    {
        // A static let with a constant value is a C# const (ADR-0038).
        var modifiers = field.IsConst
            ? Modifiers(field.Accessibility, isStatic: false) + "const "
            : Modifiers(field.Accessibility, field.IsStatic) + (field.IsReadOnly ? "readonly " : "");
        var initializer = program.Initializers.TryGetValue(field, out var value) ? $" = {Expression(value)}" : "";
        _writer.WriteMapped(_source, field.Syntax.Span, $"{modifiers}{TypeName(field.Type)} {Escape(field.Name)}{initializer};");
    }

    private void LowerMethod(SourceNamedTypeSymbol type, SourceMethodSymbol method)
    {
        var parameters = string.Join(", ", method.Parameters.Select(p => $"{TypeName(p.Type)} {Escape(p.Name)}{DefaultValue(p)}"));
        // A struct's self function can't change the value: C#'s readonly method (ADR-0008).
        var readOnly = method.IsReadOnly ? "readonly " : "";
        var header = method.MethodKind == MethodKind.Constructor
            ? $"{Modifiers(method.Accessibility, isStatic: false)}{Escape(type.Name)}({parameters})"
            : $"{Modifiers(method.Accessibility, method.IsStatic)}{readOnly}{TypeName(method.ReturnType)} {Escape(method.Name)}({parameters})";
        _writer.WriteHidden(header);
        LowerBody(method);
    }

    /// <summary>
    /// <c> = value</c> for a parameter with a default. C# takes a constant, <c>null</c> or <c>new S()</c> there: a value
    /// going into an <c>int?</c> is written without its conversion, which C# makes itself.
    /// </summary>
    private string DefaultValue(ParameterSymbol parameter) => program.DefaultValues.TryGetValue(parameter, out var value)
        ? " = " + value switch
        {
            BoundConversion { ConversionKind: ConversionKind.NullLiteral } => "null",
            BoundConversion { ConversionKind: ConversionKind.ImplicitNullable } conversion => Expression(conversion.Operand),
            _ => Expression(value),
        }
        : "";

    private void LowerBody(SourceMethodSymbol method)
    {
        var body = program.Bodies[method];
        var block = method.Syntax switch
        {
            FunctionDeclarationSyntax function => function.Body,
            InitDeclarationSyntax init => init.Body,
            AccessorDeclarationSyntax accessor => accessor.Body,
            _ => null,
        };
        // The braces are mapped too, so that a breakpoint can stop where the function starts and ends (rule 5).
        WriteBrace(block?.OpenBraceToken, "{");
        _writer.Indent();
        string[] taken = [];
        if (method is { MethodKind: MethodKind.PropertySet, Parameters: [{ Name: not "value" } parameter] })
        {
            // C# names the new value 'value'; Nyxel names it in set(v). A local named 'value' in this setter would
            // clash with C#'s, so it gets another name.
            _writer.WriteHidden($"{TypeName(parameter.Type)} {Escape(parameter.Name)} = value;");
            taken = ["value"];
        }
        _localNames = PlanLocalNames(body, taken, method.Parameters.Select(p => p.Name));
        foreach (var statement in body.Statements)
        {
            LowerStatement(statement);
        }
        _localNames = [];
        _writer.Unindent();
        WriteBrace(block?.CloseBraceToken, "}");
    }

    /// <summary>How a local is written in C#: its own name, unless C#'s scopes needed another (<see cref="PlanLocalNames"/>).</summary>
    private string LocalName(LocalSymbol local) => Escape(_localNames.TryGetValue(local, out var renamed) ? renamed : local.Name);

    private void WriteBrace(SyntaxToken? token, string brace)
    {
        if (token is { IsMissing: false } mapped)
        {
            _writer.WriteMapped(_source, mapped.Span, brace);
        }
        else
        {
            _writer.WriteHidden(brace);
        }
    }

    // Statements -----------------------------------------------------------------------------------------------

    private void LowerStatement(BoundStatement statement)
    {
        switch (statement)
        {
            case BoundBlock block:
                LowerBlock(block);
                break;
            case BoundLocalDeclaration declaration:
                var initializer = LowerStatementValue(statement, declaration.Initializer);
                Mapped(statement, $"{TypeName(declaration.Local.Type)} {LocalName(declaration.Local)} = {Expression(initializer)};");
                break;
            case BoundExpressionStatement expression:
                Mapped(statement, $"{Expression(expression.Expression)};");
                break;
            case BoundAssignment assignment:
                var assigned = LowerStatementValue(statement, assignment.Value);
                Mapped(statement, $"{Expression(assignment.Target)} = {Expression(assigned)};");
                break;
            case BoundCoalesceAssignment coalesce:
                Mapped(statement, $"{Expression(coalesce.Target)} ??= {Expression(coalesce.Value)};");
                break;
            case BoundThrow throwStatement:
                Mapped(statement, $"throw {Expression(throwStatement.Exception)};");
                break;
            case BoundCompoundAssignment compound:
                Mapped(statement, $"{Expression(compound.Target)} {OperatorText(compound.OperatorKind)}= {Expression(compound.Value)};");
                break;
            case BoundIf ifStatement:
                LowerIf(ifStatement);
                break;
            case BoundWhile loop:
                var whileSyntax = (WhileStatementSyntax)loop.Syntax;
                _writer.WriteMapped(_source, Header(whileSyntax.WhileKeyword, whileSyntax.Condition), $"while ({Expression(loop.Condition)})");
                EnterLoop();
                LowerBlock(loop.Body);
                ExitLoop();
                break;
            case BoundForRange range:
                EnterLoop();
                LowerForRange(range);
                ExitLoop();
                break;
            case BoundForEach each:
                EnterLoop();
                LowerForEach(each);
                ExitLoop();
                break;
            case BoundMatchStatement match:
                LowerMatchStatement(match);
                break;
            case BoundReturn returnStatement:
                Mapped(statement, returnStatement.Value is { } value ? $"return {Expression(value)};" : "return;");
                break;
            case BoundBreak:
                Mapped(statement, BreakText());
                break;
            case BoundContinue:
                Mapped(statement, "continue;");
                break;
        }
    }

    private void Mapped(BoundStatement statement, string line) => _writer.WriteMapped(_source, statement.Syntax.Span, line);

    /// <summary>
    /// <c>let t = a ?? return</c> (also <c>break</c>, <c>continue</c>, and <c>a ?? b ?? return</c>): C# can't leave from
    /// inside an expression, so the check comes first, mapped to the same statement, and the value is a temporary:
    /// <c>if (!(a is {} v)) return;</c>, then <c>T t = v;</c>. The binder allows these only as the value of a whole
    /// statement, under conversions at most. A <c>throw</c> stays in place: C# has <c>a ?? throw e</c>.
    /// </summary>
    private BoundExpression LowerCoalesceJump(BoundStatement statement, BoundExpression value)
    {
        var conversions = new Stack<BoundConversion>();
        var inner = value;
        while (inner is BoundConversion conversion)
        {
            conversions.Push(conversion);
            inner = conversion.Operand;
        }
        if (inner is not BoundCoalesce coalesce || LastJump(coalesce) is not { } jump || jump is BoundThrow)
        {
            return value;
        }

        // a ?? b ?? return: the values in order, then the jump.
        var values = new List<BoundExpression>();
        for (BoundExpression? part = coalesce; part is BoundCoalesce link; part = link.Right)
        {
            values.Add(link.Left);
        }
        var text = string.Join(" ?? ", values.Select(v => Expression(v, CoalescePrecedence + 1)));
        var temporary = Temporary("value");
        var check = values.Count == 1 ? Expression(values[0], UnaryPrecedence) : $"({text})";
        Mapped(statement, $"if (!({check} is {{}} {temporary})) {JumpText(jump)}");

        BoundExpression result = new BoundTemporary(coalesce.Syntax, temporary, coalesce.Type);
        while (conversions.TryPop(out var conversion))
        {
            result = new BoundConversion(conversion.Syntax, result, conversion.ConversionKind, conversion.Type, conversion.IsExplicit);
        }
        return result;

        static BoundStatement? LastJump(BoundCoalesce coalesce) =>
            coalesce.Jump ?? (coalesce.Right is BoundCoalesce next ? LastJump(next) : null);
    }

    private string JumpText(BoundStatement jump) => jump switch
    {
        BoundReturn { Value: { } returned } => $"return {Expression(returned)};",
        BoundReturn => "return;",
        BoundBreak => BreakText(),
        BoundContinue => "continue;",
        _ => throw new InvalidOperationException($"{jump.GetType().Name} after '??' can't be lowered."),
    };

    private static TextSpan Header(SyntaxToken keyword, SyntaxNode last) => TextSpan.FromBounds(keyword.Span.Start, last.Span.End);

    private void LowerBlock(BoundBlock block)
    {
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var statement in block.Statements)
        {
            LowerStatement(statement);
        }
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    private void LowerIf(BoundIf ifStatement)
    {
        var syntax = (IfStatementSyntax)ifStatement.Syntax;
        _writer.WriteMapped(_source, Header(syntax.IfKeyword, syntax.Condition), $"if ({Expression(ifStatement.Condition)})");
        LowerBlock((BoundBlock)ifStatement.Then);
        switch (ifStatement.Else)
        {
            case BoundIf elseIf:
                _writer.WriteHidden("else");
                LowerIf(elseIf);
                break;
            case BoundBlock elseBlock:
                _writer.WriteHidden("else");
                LowerBlock(elseBlock);
                break;
        }
    }

    /// <summary>
    /// <c>for i in a..&lt;b</c>: the ends are evaluated once, and <c>i</c> is a new <c>let</c> in every iteration,
    /// as in a Nyxel loop; the counter is a separate C# variable. Each part of the C# header is on its own line, so
    /// each has its own sequence point mapped to the Nyxel header (rule 2).
    /// </summary>
    private void LowerForRange(BoundForRange range)
    {
        var syntax = (ForStatementSyntax)range.Syntax;
        var header = Header(syntax.ForKeyword, syntax.Collection);
        var type = TypeName(range.Variable.Type);
        var counter = Temporary("i");
        var end = Temporary("end");
        _writer.WriteMapped(_source, header, $"for ({type} {counter} = {Expression(range.From)}, {end} = {Expression(range.To)};");
        _writer.WriteMapped(_source, header, $"{counter} {(range.IncludesEnd ? "<=" : "<")} {end};");
        _writer.WriteMapped(_source, header, $"{counter}++)");
        _writer.WriteHidden("{");
        _writer.Indent();
        _writer.WriteHidden($"{type} {LocalName(range.Variable)} = {counter};");
        LowerBlock(range.Body);
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    private void LowerForEach(BoundForEach each)
    {
        var syntax = (ForStatementSyntax)each.Syntax;
        var header = Header(syntax.ForKeyword, syntax.Collection);
        _writer.WriteMapped(_source, header, $"foreach ({TypeName(each.Variable.Type)} {LocalName(each.Variable)}");
        _writer.WriteMapped(_source, header, $"in {Expression(each.Collection)})");
        LowerBlock(each.Body);
    }

    private string Temporary(string name) => $"__nyxel_{name}{++_temporaries}";

    // Expressions ----------------------------------------------------------------------------------------------

    private const int PrimaryPrecedence = 16;
    private const int UnaryPrecedence = 15;
    private const int RelationalPrecedence = 11;
    private const int EqualityPrecedence = 10;
    private const int CoalescePrecedence = 4;

    private string Expression(BoundExpression expression, int parentPrecedence = 0)
    {
        var (text, precedence) = ExpressionCore(expression);
        return precedence < parentPrecedence ? $"({text})" : text;
    }

    private (string Text, int Precedence) ExpressionCore(BoundExpression expression)
    {
        switch (expression)
        {
            case BoundLiteral { Value: null }:
                return ("null", PrimaryPrecedence);
            case BoundLiteral literal:
                return Literal(literal.Value);
            case BoundLocalAccess local:
                return Narrowed(LocalName(local.Local), local.Local.Type, local.Type);
            case BoundParameterAccess parameter:
                return Narrowed(Escape(parameter.Parameter.Name), parameter.Parameter.Type, parameter.Type);
            case BoundTemporary temporary:
                return (temporary.Name, PrimaryPrecedence);
            case BoundConditionalReceiver:
                // Inside the access of 'a?.B': C# writes nothing there ('a?' + '.B').
                return ("", PrimaryPrecedence);
            case BoundConditionalAccess conditional:
                return ($"{Expression(conditional.Receiver, PrimaryPrecedence)}?{Expression(conditional.Access)}", PrimaryPrecedence);
            case BoundNullCheck check:
                // Whether the reference is null, never an overloaded == (ADR-0023).
                return ($"{Expression(check.Operand, RelationalPrecedence + 1)} {(check.IsNull ? "is null" : "is not null")}", RelationalPrecedence);
            case BoundIsType isType:
                return ($"{Expression(isType.Operand, RelationalPrecedence + 1)} {(isType.IsNegated ? "is not" : "is")} {TypeName(isType.TestedType)}", RelationalPrecedence);
            case BoundIsCase { Case: SourceEnumCaseSymbol { ContainingType: { IsDataEnum: true, TypeKind: TypeKind.Struct } structEnum } structCase } isCase:
                // A struct enum is a union to C# 15, whose patterns test the case types: the tag says the case
                // (ADR-0046). An E? or an object goes through the enum's helper, which also says no to null.
                if (ReferenceEquals(isCase.Operand.Type, structEnum))
                {
                    return ($"{Expression(isCase.Operand, PrimaryPrecedence)}.{StructEnumTag} {(isCase.IsNegated ? "!=" : "==")} {structCase.Ordinal}", EqualityPrecedence);
                }
                var tested = isCase.Operand.Type is NullableTypeSymbol ? Expression(isCase.Operand) : $"{Expression(isCase.Operand, RelationalPrecedence + 1)} as {TypeName(structEnum)}?";
                return ($"{(isCase.IsNegated ? "!" : "")}{TypeName(structEnum)}.{StructEnumIs}({tested}, {structCase.Ordinal})", UnaryPrecedence);
            case BoundIsCase isCase:
                // C#'s constant pattern: the same meaning for a value, an E? and an object (ADR-0040). An alias is a
                // const of the enum's extension class (ADR-0045). A class enum's case is its type (ADR-0046).
                var pattern = isCase.Case switch
                {
                    SourceEnumCaseSymbol { ContainingType.IsDataEnum: true } classCase => CaseTypeName(classCase),
                    SourceFieldSymbol alias => $"{ExtensionsName(alias.ContainingType)}.{Escape(alias.Name)}",
                    var constant => $"{TypeName(constant.ContainingType)}.{Escape(constant.Name)}",
                };
                return ($"{Expression(isCase.Operand, RelationalPrecedence + 1)} {(isCase.IsNegated ? "is not" : "is")} {pattern}", RelationalPrecedence);
            case BoundCoalesce coalesce:
                var right = coalesce switch
                {
                    { Right: { } value } => Expression(value, CoalescePrecedence),
                    { Jump: BoundThrow thrown } => $"throw {Expression(thrown.Exception)}",
                    _ => throw new InvalidOperationException("'?? return' inside a larger expression; binding should have reported it."),
                };
                return ($"{Expression(coalesce.Left, CoalescePrecedence + 1)} ?? {right}", CoalescePrecedence);
            case BoundSelf:
                return (_self, PrimaryPrecedence);
            case BoundFieldAccess field:
                return ($"{FieldOwner(field)}.{Escape(field.Field.Name)}", PrimaryPrecedence);
            case BoundPropertyAccess property when IsNyxelEnum(property.Property.ContainingType):
                // The getter of an extension property, called as the static method C# makes of it.
                return ($"{ExtensionsName(property.Property.ContainingType)}.get_{property.Property.Name}({(property.Receiver is { } owner ? Expression(owner) : "")})", PrimaryPrecedence);
            case BoundPropertyAccess property:
                return ($"{Receiver(property.Receiver, property.Property.ContainingType)}.{Escape(property.Property.Name)}", PrimaryPrecedence);
            case BoundIndexerAccess indexer:
                return ($"{Expression(indexer.Receiver, PrimaryPrecedence)}[{Arguments(indexer.Arguments)}]", PrimaryPrecedence);
            case BoundArrayAccess array:
                return ($"{Expression(array.Array, PrimaryPrecedence)}[{string.Join(", ", array.Indices.Select(i => Expression(i)))}]", PrimaryPrecedence);
            case BoundCall call when IsNyxelEnum(call.Method.ContainingType):
                // An enum's function is an extension member: called through its class, with the value first. C# would
                // look 'Element.Parse' up on System.Enum before the extensions, and the class isn't imported anyway.
                var receiverAndArguments = string.Join(", ", new[] { call.Receiver is { } enumValue ? Expression(enumValue) : null, Arguments(call.Arguments) }.Where(s => !string.IsNullOrEmpty(s)));
                return ($"{ExtensionsName(call.Method.ContainingType)}.{Escape(call.Method.Name)}({receiverAndArguments})", PrimaryPrecedence);
            case BoundCall call:
                return ($"{Receiver(call.Receiver, call.Method.ContainingType)}.{Escape(call.Method.Name)}({Arguments(call.Arguments)})", PrimaryPrecedence);
            case BoundObjectCreation creation:
                return ($"new {TypeName(creation.Type)}({Arguments(creation.Arguments)})", PrimaryPrecedence);
            case BoundEnumCase { Case: var @case } enumCase:
                // A class enum's case without data is its one shared object; a struct enum's value is made from the
                // case's own struct (ADR-0046). Named data goes by the constructor's camelCase names.
                var data = string.Join(", ", enumCase.Arguments.Select(a => a.Name is null ? Expression(a.Value) : $"{CaseParameter(a.Parameter)}: {Expression(a.Value)}"));
                var created = $"new {CaseTypeName(@case)}({data})";
                return @case.ContainingType.TypeKind == TypeKind.Class
                    ? (@case.HasData ? created : $"{TypeName(@case.ContainingType)}.{SharedCaseField(@case)}", PrimaryPrecedence)
                    : ($"new {TypeName(@case.ContainingType)}({created})", PrimaryPrecedence);
            case BoundArrayCreation array:
                return (ArrayCreation(array), PrimaryPrecedence);
            case BoundUnary unary:
                var operand = Expression(unary.Operand, UnaryPrecedence);
                var op = unary.OperatorKind switch
                {
                    UnaryOperatorKind.Negate => "-",
                    UnaryOperatorKind.Plus => "+",
                    UnaryOperatorKind.BitwiseNot => "~",
                    _ => "!",
                };
                // '- -x' must not become '--x'.
                return (operand.StartsWith(op, StringComparison.Ordinal) ? $"{op}({operand})" : op + operand, UnaryPrecedence);
            case BoundBinary binary:
                var precedence = Precedence(binary.OperatorKind);
                return ($"{Expression(binary.Left, precedence)} {OperatorText(binary.OperatorKind)} {Expression(binary.Right, precedence + 1)}", precedence);
            case BoundConversion conversion:
                // Numeric conversions are written as casts even where C# would convert implicitly, so that the C#
                // operations and overloads are the ones the binder chose; reference conversions need nothing. A value
                // to a Nullable<T> and null to a T? are cast for the same reason (null alone has no type in C#).
                if (conversion.IsExplicit || conversion.ConversionKind is ConversionKind.ImplicitNumeric or ConversionKind.ExplicitNumeric
                    || (conversion.ConversionKind == ConversionKind.ImplicitNullable && conversion.Type.IsValueType)
                    || conversion.ConversionKind == ConversionKind.NullLiteral)
                {
                    var inner = Expression(conversion.Operand, PrimaryPrecedence);
                    return ($"({TypeName(conversion.Type)}){inner}", UnaryPrecedence);
                }
                return ExpressionCore(conversion.Operand);
            case BoundInterpolatedString interpolated:
                return (InterpolatedString(interpolated), PrimaryPrecedence);
            case BoundMatchExpression match:
                return MatchExpression(match);
            default:
                throw new InvalidOperationException($"{expression.GetType().Name} can't be lowered; binding should have reported an error.");
        }
    }

    /// <summary>
    /// A local or parameter read where a check narrowed it: C# needs a cast to the narrower type, except from a
    /// reference type's <c>T?</c> to its <c>T</c>, which is the same C# type.
    /// </summary>
    private static (string Text, int Precedence) Narrowed(string name, TypeSymbol declared, TypeSymbol type) =>
        ReferenceEquals(declared, type) || (declared.IsReferenceType && ReferenceEquals(declared.NonNullable, type.NonNullable))
            ? (name, PrimaryPrecedence)
            : ($"(({TypeName(type)}){name})", PrimaryPrecedence);

    private string Receiver(BoundExpression? receiver, NamedTypeSymbol containingType) =>
        receiver is null ? TypeName(containingType) : Expression(receiver, PrimaryPrecedence);

    /// <summary>What a field is read through: its receiver, its type, or for a Nyxel enum's static let the enum's extension class.</summary>
    private string FieldOwner(BoundFieldAccess field) =>
        field.Field is SourceFieldSymbol && IsNyxelEnum(field.Field.ContainingType)
            ? ExtensionsName(field.Field.ContainingType)
            : Receiver(field.Receiver, field.Field.ContainingType);

    private string Arguments(IEnumerable<BoundArgument> arguments) =>
        string.Join(", ", arguments.Select(a => a.Name is { } name ? $"{Escape(name)}: {Expression(a.Value)}" : Expression(a.Value)));

    /// <summary><c>new int[n]</c>; for an array of arrays the lengths go to the outermost one: <c>new int[n][]</c>.</summary>
    private string ArrayCreation(BoundArrayCreation array)
    {
        var element = ((ArrayTypeSymbol)array.Type).ElementType;
        var suffix = new StringBuilder();
        while (element is ArrayTypeSymbol inner)
        {
            suffix.Append(Ranks(inner.Rank));
            element = inner.ElementType;
        }
        return $"new {TypeName(element)}[{string.Join(", ", array.Lengths.Select(l => Expression(l)))}]{suffix}";
    }

    private string InterpolatedString(BoundInterpolatedString interpolated)
    {
        var builder = new StringBuilder("$\"");
        foreach (var part in interpolated.Parts)
        {
            if (part.Text is { } text)
            {
                builder.Append(CSharpLiteral.FormatLiteral(text, quote: false).Replace("{", "{{", StringComparison.Ordinal).Replace("}", "}}", StringComparison.Ordinal));
                continue;
            }
            // Parentheses keep a ':' inside the expression (global::) from starting the format.
            builder.Append("{(").Append(Expression(part.Value!)).Append(')');
            if (part.Alignment is { } alignment)
            {
                builder.Append(',').Append(Expression(alignment));
            }
            if (part.Format is { } format)
            {
                builder.Append(':').Append(format);
            }
            builder.Append('}');
        }
        return builder.Append('"').ToString();
    }

    private static (string Text, int Precedence) Literal(object? value)
    {
        var text = value switch
        {
            bool boolean => boolean ? "true" : "false",
            string text1 => CSharpLiteral.FormatLiteral(text1, quote: true),
            char character => CSharpLiteral.FormatLiteral(character, quote: true),
            int number => number.ToString(CultureInfo.InvariantCulture),
            uint number => number.ToString(CultureInfo.InvariantCulture) + "u",
            long number => number.ToString(CultureInfo.InvariantCulture) + "L",
            ulong number => number.ToString(CultureInfo.InvariantCulture) + "UL",
            float number => number.ToString("R", CultureInfo.InvariantCulture) + "f",
            double number => number.ToString("R", CultureInfo.InvariantCulture) + "d",
            decimal number => number.ToString(CultureInfo.InvariantCulture) + "m",
            sbyte number => $"(sbyte){Signed(number)}",
            byte number => $"(byte){number}",
            short number => $"(short){Signed(number)}",
            ushort number => $"(ushort){number}",
            _ => throw new InvalidOperationException($"Unexpected constant {value}."),
        };
        return (text, text.StartsWith('-') || text.StartsWith('(') ? UnaryPrecedence : PrimaryPrecedence);

        static string Signed(long number) => number < 0 ? $"({number})" : number.ToString(CultureInfo.InvariantCulture);
    }

    private static int Precedence(BinaryOperatorKind operatorKind) => operatorKind switch
    {
        BinaryOperatorKind.Multiply or BinaryOperatorKind.Divide or BinaryOperatorKind.Modulo => 14,
        BinaryOperatorKind.Add or BinaryOperatorKind.Subtract => 13,
        BinaryOperatorKind.LeftShift or BinaryOperatorKind.RightShift => 12,
        BinaryOperatorKind.Less or BinaryOperatorKind.LessOrEqual or BinaryOperatorKind.Greater or BinaryOperatorKind.GreaterOrEqual => 11,
        BinaryOperatorKind.Equal or BinaryOperatorKind.NotEqual => 10,
        BinaryOperatorKind.BitwiseAnd => 9,
        BinaryOperatorKind.ExclusiveOr => 8,
        BinaryOperatorKind.BitwiseOr => 7,
        BinaryOperatorKind.LogicalAnd => 6,
        _ => 5,
    };

    private static string OperatorText(BinaryOperatorKind operatorKind) => operatorKind switch
    {
        BinaryOperatorKind.Add => "+",
        BinaryOperatorKind.Subtract => "-",
        BinaryOperatorKind.Multiply => "*",
        BinaryOperatorKind.Divide => "/",
        BinaryOperatorKind.Modulo => "%",
        BinaryOperatorKind.LeftShift => "<<",
        BinaryOperatorKind.RightShift => ">>",
        BinaryOperatorKind.Less => "<",
        BinaryOperatorKind.LessOrEqual => "<=",
        BinaryOperatorKind.Greater => ">",
        BinaryOperatorKind.GreaterOrEqual => ">=",
        BinaryOperatorKind.Equal => "==",
        BinaryOperatorKind.NotEqual => "!=",
        BinaryOperatorKind.BitwiseAnd => "&",
        BinaryOperatorKind.BitwiseOr => "|",
        BinaryOperatorKind.ExclusiveOr => "^",
        BinaryOperatorKind.LogicalAnd => "&&",
        _ => "||",
    };

