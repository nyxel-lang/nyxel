using System.Globalization;
using System.Text;
using Nyxel.Compiler.Binding;
using Nyxel.Compiler.Symbols;
using Nyxel.Compiler.Syntax;
using Nyxel.Compiler.Text;
using CSharpFacts = Microsoft.CodeAnalysis.CSharp.SyntaxFacts;
using CSharpLiteral = Microsoft.CodeAnalysis.CSharp.SymbolDisplay;

namespace Nyxel.Compiler.Lowering;

/// <summary>
/// Lowering (docs/design/lowering.md): the bound program as C# source. Every Nyxel statement is one C# line with a
/// <c>#line</c> span directive back to it (docs/design/debug-mapping.md); types are written in full with
/// <c>global::</c>, so C#'s name lookup has nothing to decide.
/// </summary>
internal sealed class Lowerer(BoundProgram program)
{
    private readonly CSharpWriter _writer = new();
    private SourceText _source = null!;
    private int _temporaries;

    public static string Lower(BoundProgram program) => new Lowerer(program).LowerProgram();

    private string LowerProgram()
    {
        _writer.WriteRaw("// <auto-generated>Generated by the Nyxel compiler from .nyxel files.</auto-generated>");
        _writer.WriteRaw("#nullable disable");
        _writer.WriteRaw("#pragma warning disable");
        foreach (var group in program.Types.GroupBy(t => t.ContainingNamespace))
        {
            var ns = group.Key;
            if (!ns.IsGlobal)
            {
                _writer.WriteHidden($"namespace {string.Join(".", ns.FullName.Split('.').Select(Escape))}");
                _writer.WriteHidden("{");
                _writer.Indent();
            }
            foreach (var type in group)
            {
                LowerType(type);
            }
            if (!ns.IsGlobal)
            {
                _writer.Unindent();
                _writer.WriteHidden("}");
            }
        }
        return _writer.ToString();
    }

    private void LowerType(SourceNamedTypeSymbol type)
    {
        _source = type.SyntaxTree.Text;
        var access = type.Accessibility == Accessibility.Public ? "public" : "internal";
        _writer.WriteHidden($"{access} class {Escape(type.Name)}");
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var member in type.GetMembers())
        {
            switch (member)
            {
                case SourceFieldSymbol field:
                    LowerField(field);
                    break;
                case SourceMethodSymbol { Syntax: not null } method:
                    LowerMethod(type, method);
                    break;
            }
        }
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    private void LowerField(SourceFieldSymbol field)
    {
        var modifiers = Modifiers(field.Accessibility, field.IsStatic) + (field.IsReadOnly ? "readonly " : "");
        var initializer = program.FieldInitializers.TryGetValue(field, out var value) ? $" = {Expression(value)}" : "";
        _writer.WriteMapped(_source, field.Syntax.Span, $"{modifiers}{TypeName(field.Type)} {Escape(field.Name)}{initializer};");
    }

    private void LowerMethod(SourceNamedTypeSymbol type, SourceMethodSymbol method)
    {
        var parameters = string.Join(", ", method.Parameters.Select(p => $"{TypeName(p.Type)} {Escape(p.Name)}"));
        var header = method.MethodKind == MethodKind.Constructor
            ? $"{Modifiers(method.Accessibility, isStatic: false)}{Escape(type.Name)}({parameters})"
            : $"{Modifiers(method.Accessibility, method.IsStatic)}{TypeName(method.ReturnType)} {Escape(method.Name)}({parameters})";
        _writer.WriteHidden(header);

        var body = program.Bodies[method];
        var block = method.Syntax switch
        {
            FunctionDeclarationSyntax function => function.Body,
            InitDeclarationSyntax init => init.Body,
            _ => null,
        };
        // The braces are mapped too, so that a breakpoint can stop where the function starts and ends (rule 5).
        WriteBrace(block?.OpenBraceToken, "{");
        _writer.Indent();
        foreach (var statement in body.Statements)
        {
            LowerStatement(statement);
        }
        _writer.Unindent();
        WriteBrace(block?.CloseBraceToken, "}");
    }

    private void WriteBrace(SyntaxToken? token, string brace)
    {
        if (token is { IsMissing: false } mapped)
        {
            _writer.WriteMapped(_source, mapped.Span, brace);
        }
        else
        {
            _writer.WriteHidden(brace);
        }
    }

    // Statements -----------------------------------------------------------------------------------------------

    private void LowerStatement(BoundStatement statement)
    {
        switch (statement)
        {
            case BoundBlock block:
                LowerBlock(block);
                break;
            case BoundLocalDeclaration declaration:
                Mapped(statement, $"{TypeName(declaration.Local.Type)} {Escape(declaration.Local.Name)} = {Expression(declaration.Initializer)};");
                break;
            case BoundExpressionStatement expression:
                Mapped(statement, $"{Expression(expression.Expression)};");
                break;
            case BoundAssignment assignment:
                Mapped(statement, $"{Expression(assignment.Target)} = {Expression(assignment.Value)};");
                break;
            case BoundCompoundAssignment compound:
                Mapped(statement, $"{Expression(compound.Target)} {OperatorText(compound.OperatorKind)}= {Expression(compound.Value)};");
                break;
            case BoundIf ifStatement:
                LowerIf(ifStatement);
                break;
            case BoundWhile loop:
                var whileSyntax = (WhileStatementSyntax)loop.Syntax;
                _writer.WriteMapped(_source, Header(whileSyntax.WhileKeyword, whileSyntax.Condition), $"while ({Expression(loop.Condition)})");
                LowerBlock(loop.Body);
                break;
            case BoundForRange range:
                LowerForRange(range);
                break;
            case BoundForEach each:
                LowerForEach(each);
                break;
            case BoundReturn returnStatement:
                Mapped(statement, returnStatement.Value is { } value ? $"return {Expression(value)};" : "return;");
                break;
            case BoundBreak:
                Mapped(statement, "break;");
                break;
            case BoundContinue:
                Mapped(statement, "continue;");
                break;
        }
    }

    private void Mapped(BoundStatement statement, string line) => _writer.WriteMapped(_source, statement.Syntax.Span, line);

    private static TextSpan Header(SyntaxToken keyword, SyntaxNode last) => TextSpan.FromBounds(keyword.Span.Start, last.Span.End);

    private void LowerBlock(BoundBlock block)
    {
        _writer.WriteHidden("{");
        _writer.Indent();
        foreach (var statement in block.Statements)
        {
            LowerStatement(statement);
        }
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    private void LowerIf(BoundIf ifStatement)
    {
        var syntax = (IfStatementSyntax)ifStatement.Syntax;
        _writer.WriteMapped(_source, Header(syntax.IfKeyword, syntax.Condition), $"if ({Expression(ifStatement.Condition)})");
        LowerBlock((BoundBlock)ifStatement.Then);
        switch (ifStatement.Else)
        {
            case BoundIf elseIf:
                _writer.WriteHidden("else");
                LowerIf(elseIf);
                break;
            case BoundBlock elseBlock:
                _writer.WriteHidden("else");
                LowerBlock(elseBlock);
                break;
        }
    }

    /// <summary>
    /// <c>for i in a..&lt;b</c>: the ends are evaluated once, and <c>i</c> is a new <c>let</c> in every iteration,
    /// as in a Nyxel loop; the counter is a separate C# variable. Each part of the C# header is on its own line, so
    /// each has its own sequence point mapped to the Nyxel header (rule 2).
    /// </summary>
    private void LowerForRange(BoundForRange range)
    {
        var syntax = (ForStatementSyntax)range.Syntax;
        var header = Header(syntax.ForKeyword, syntax.Collection);
        var type = TypeName(range.Variable.Type);
        var counter = Temporary("i");
        var end = Temporary("end");
        _writer.WriteMapped(_source, header, $"for ({type} {counter} = {Expression(range.From)}, {end} = {Expression(range.To)};");
        _writer.WriteMapped(_source, header, $"{counter} {(range.IncludesEnd ? "<=" : "<")} {end};");
        _writer.WriteMapped(_source, header, $"{counter}++)");
        _writer.WriteHidden("{");
        _writer.Indent();
        _writer.WriteHidden($"{type} {Escape(range.Variable.Name)} = {counter};");
        LowerBlock(range.Body);
        _writer.Unindent();
        _writer.WriteHidden("}");
    }

    private void LowerForEach(BoundForEach each)
    {
        var syntax = (ForStatementSyntax)each.Syntax;
        var header = Header(syntax.ForKeyword, syntax.Collection);
        _writer.WriteMapped(_source, header, $"foreach ({TypeName(each.Variable.Type)} {Escape(each.Variable.Name)}");
        _writer.WriteMapped(_source, header, $"in {Expression(each.Collection)})");
        LowerBlock(each.Body);
    }

    private string Temporary(string name) => $"__nyxel_{name}{++_temporaries}";

    // Expressions ----------------------------------------------------------------------------------------------

    private const int PrimaryPrecedence = 16;
    private const int UnaryPrecedence = 15;

    private string Expression(BoundExpression expression, int parentPrecedence = 0)
    {
        var (text, precedence) = ExpressionCore(expression);
        return precedence < parentPrecedence ? $"({text})" : text;
    }

    private (string Text, int Precedence) ExpressionCore(BoundExpression expression)
    {
        switch (expression)
        {
            case BoundLiteral literal:
                return Literal(literal.Value);
            case BoundLocalAccess local:
                return (Escape(local.Local.Name), PrimaryPrecedence);
            case BoundParameterAccess parameter:
                return (Escape(parameter.Parameter.Name), PrimaryPrecedence);
            case BoundSelf:
                return ("this", PrimaryPrecedence);
            case BoundFieldAccess field:
                return ($"{Receiver(field.Receiver, field.Field.ContainingType)}.{Escape(field.Field.Name)}", PrimaryPrecedence);
            case BoundPropertyAccess property:
                return ($"{Receiver(property.Receiver, property.Property.ContainingType)}.{Escape(property.Property.Name)}", PrimaryPrecedence);
            case BoundIndexerAccess indexer:
                return ($"{Expression(indexer.Receiver, PrimaryPrecedence)}[{Arguments(indexer.Arguments)}]", PrimaryPrecedence);
            case BoundArrayAccess array:
                return ($"{Expression(array.Array, PrimaryPrecedence)}[{string.Join(", ", array.Indices.Select(i => Expression(i)))}]", PrimaryPrecedence);
            case BoundCall call:
                return ($"{Receiver(call.Receiver, call.Method.ContainingType)}.{Escape(call.Method.Name)}({Arguments(call.Arguments)})", PrimaryPrecedence);
            case BoundObjectCreation creation:
                return ($"new {TypeName(creation.Type)}({Arguments(creation.Arguments)})", PrimaryPrecedence);
            case BoundArrayCreation array:
                return (ArrayCreation(array), PrimaryPrecedence);
            case BoundUnary unary:
                var operand = Expression(unary.Operand, UnaryPrecedence);
                var op = unary.OperatorKind switch
                {
                    UnaryOperatorKind.Negate => "-",
                    UnaryOperatorKind.Plus => "+",
                    UnaryOperatorKind.BitwiseNot => "~",
                    _ => "!",
                };
                // '- -x' must not become '--x'.
                return (operand.StartsWith(op, StringComparison.Ordinal) ? $"{op}({operand})" : op + operand, UnaryPrecedence);
            case BoundBinary binary:
                var precedence = Precedence(binary.OperatorKind);
                return ($"{Expression(binary.Left, precedence)} {OperatorText(binary.OperatorKind)} {Expression(binary.Right, precedence + 1)}", precedence);
            case BoundConversion conversion:
                // Numeric conversions are written as casts even where C# would convert implicitly, so that the C#
                // operations and overloads are the ones the binder chose; reference conversions need nothing.
                if (conversion.IsExplicit || conversion.ConversionKind is ConversionKind.ImplicitNumeric or ConversionKind.ExplicitNumeric)
                {
                    var inner = Expression(conversion.Operand, PrimaryPrecedence);
                    return ($"({TypeName(conversion.Type)}){inner}", UnaryPrecedence);
                }
                return ExpressionCore(conversion.Operand);
            case BoundInterpolatedString interpolated:
                return (InterpolatedString(interpolated), PrimaryPrecedence);
            default:
                throw new InvalidOperationException($"{expression.GetType().Name} can't be lowered; binding should have reported an error.");
        }
    }

    private string Receiver(BoundExpression? receiver, NamedTypeSymbol containingType) =>
        receiver is null ? TypeName(containingType) : Expression(receiver, PrimaryPrecedence);

    private string Arguments(IEnumerable<BoundArgument> arguments) =>
        string.Join(", ", arguments.Select(a => a.Name is { } name ? $"{Escape(name)}: {Expression(a.Value)}" : Expression(a.Value)));

    /// <summary><c>new int[n]</c>; for an array of arrays the lengths go to the outermost one: <c>new int[n][]</c>.</summary>
    private string ArrayCreation(BoundArrayCreation array)
    {
        var element = ((ArrayTypeSymbol)array.Type).ElementType;
        var suffix = new StringBuilder();
        while (element is ArrayTypeSymbol inner)
        {
            suffix.Append(Ranks(inner.Rank));
            element = inner.ElementType;
        }
        return $"new {TypeName(element)}[{string.Join(", ", array.Lengths.Select(l => Expression(l)))}]{suffix}";
    }

    private string InterpolatedString(BoundInterpolatedString interpolated)
    {
        var builder = new StringBuilder("$\"");
        foreach (var part in interpolated.Parts)
        {
            if (part.Text is { } text)
            {
                builder.Append(CSharpLiteral.FormatLiteral(text, quote: false).Replace("{", "{{", StringComparison.Ordinal).Replace("}", "}}", StringComparison.Ordinal));
                continue;
            }
            // Parentheses keep a ':' inside the expression (global::) from starting the format.
            builder.Append("{(").Append(Expression(part.Value!)).Append(')');
            if (part.Alignment is { } alignment)
            {
                builder.Append(',').Append(Expression(alignment));
            }
            if (part.Format is { } format)
            {
                builder.Append(':').Append(format);
            }
            builder.Append('}');
        }
        return builder.Append('"').ToString();
    }

    private static (string Text, int Precedence) Literal(object? value)
    {
        var text = value switch
        {
            bool boolean => boolean ? "true" : "false",
            string text1 => CSharpLiteral.FormatLiteral(text1, quote: true),
            char character => CSharpLiteral.FormatLiteral(character, quote: true),
            int number => number.ToString(CultureInfo.InvariantCulture),
            uint number => number.ToString(CultureInfo.InvariantCulture) + "u",
            long number => number.ToString(CultureInfo.InvariantCulture) + "L",
            ulong number => number.ToString(CultureInfo.InvariantCulture) + "UL",
            float number => number.ToString("R", CultureInfo.InvariantCulture) + "f",
            double number => number.ToString("R", CultureInfo.InvariantCulture) + "d",
            decimal number => number.ToString(CultureInfo.InvariantCulture) + "m",
            sbyte number => $"(sbyte){Signed(number)}",
            byte number => $"(byte){number}",
            short number => $"(short){Signed(number)}",
            ushort number => $"(ushort){number}",
            _ => throw new InvalidOperationException($"Unexpected constant {value}."),
        };
        return (text, text.StartsWith('-') || text.StartsWith('(') ? UnaryPrecedence : PrimaryPrecedence);

        static string Signed(long number) => number < 0 ? $"({number})" : number.ToString(CultureInfo.InvariantCulture);
    }

    private static int Precedence(BinaryOperatorKind operatorKind) => operatorKind switch
    {
        BinaryOperatorKind.Multiply or BinaryOperatorKind.Divide or BinaryOperatorKind.Modulo => 14,
        BinaryOperatorKind.Add or BinaryOperatorKind.Subtract => 13,
        BinaryOperatorKind.LeftShift or BinaryOperatorKind.RightShift => 12,
        BinaryOperatorKind.Less or BinaryOperatorKind.LessOrEqual or BinaryOperatorKind.Greater or BinaryOperatorKind.GreaterOrEqual => 11,
        BinaryOperatorKind.Equal or BinaryOperatorKind.NotEqual => 10,
        BinaryOperatorKind.BitwiseAnd => 9,
        BinaryOperatorKind.ExclusiveOr => 8,
        BinaryOperatorKind.BitwiseOr => 7,
        BinaryOperatorKind.LogicalAnd => 6,
        _ => 5,
    };

    private static string OperatorText(BinaryOperatorKind operatorKind) => operatorKind switch
    {
        BinaryOperatorKind.Add => "+",
        BinaryOperatorKind.Subtract => "-",
        BinaryOperatorKind.Multiply => "*",
        BinaryOperatorKind.Divide => "/",
        BinaryOperatorKind.Modulo => "%",
        BinaryOperatorKind.LeftShift => "<<",
        BinaryOperatorKind.RightShift => ">>",
        BinaryOperatorKind.Less => "<",
        BinaryOperatorKind.LessOrEqual => "<=",
        BinaryOperatorKind.Greater => ">",
        BinaryOperatorKind.GreaterOrEqual => ">=",
        BinaryOperatorKind.Equal => "==",
        BinaryOperatorKind.NotEqual => "!=",
        BinaryOperatorKind.BitwiseAnd => "&",
        BinaryOperatorKind.BitwiseOr => "|",
        BinaryOperatorKind.ExclusiveOr => "^",
        BinaryOperatorKind.LogicalAnd => "&&",
        _ => "||",
    };

    // Names --------------------------------------------------------------------------------------------------

    private static string Modifiers(Accessibility accessibility, bool isStatic) =>
        accessibility switch
        {
            Accessibility.Public => "public ",
            Accessibility.Protected => "protected ",
            Accessibility.Internal => "internal ",
            _ => "private ",
        } + (isStatic ? "static " : "");

    /// <summary>A type as C# writes it in full: <c>global::System.Collections.Generic.List&lt;int&gt;</c>, <c>int[,]</c>.</summary>
    public static string TypeName(TypeSymbol type)
    {
        switch (type)
        {
            case ArrayTypeSymbol array:
                var element = array.ElementType;
                var ranks = new StringBuilder(Ranks(array.Rank));
                while (element is ArrayTypeSymbol inner)
                {
                    ranks.Append(Ranks(inner.Rank));
                    element = inner.ElementType;
                }
                return TypeName(element) + ranks;
            case NamedTypeSymbol named when SymbolDisplay.Keyword(named.SpecialType) is { } keyword:
                return keyword;
            case NamedTypeSymbol named:
                var outer = named.ContainingType is { } containing
                    ? TypeName(containing)
                    : named.ContainingNamespace is { IsGlobal: false } ns ? "global::" + string.Join(".", ns.FullName.Split('.').Select(Escape)) : "global:";
                var separator = named.ContainingType is null && named.ContainingNamespace is null or { IsGlobal: true } ? ":" : ".";
                var arguments = named.Arity > 0 ? $"<{string.Join(", ", named.TypeArguments.Select(TypeName))}>" : "";
                return $"{outer}{separator}{Escape(named.Name)}{arguments}";
            default:
                return Escape(type.Name);
        }
    }

    private static string Ranks(int rank) => $"[{new string(',', rank - 1)}]";

    /// <summary>A Nyxel name that is a C# keyword (<c>base</c>, <c>params</c>) is written with <c>@</c>.</summary>
    private static string Escape(string name) =>
        CSharpFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;
}
