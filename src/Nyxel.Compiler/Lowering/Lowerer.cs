    private static string Modifiers(Accessibility accessibility, bool isStatic) =>
        accessibility switch
        {
            Accessibility.Public => "public ",
            Accessibility.Protected => "protected ",
            Accessibility.Internal => "internal ",
            _ => "private ",
        } + (isStatic ? "static " : "");

    /// <summary>A type as C# writes it in full: <c>global::System.Collections.Generic.List&lt;int&gt;</c>, <c>int[,]</c>.</summary>
    public static string TypeName(TypeSymbol type)
    {
        switch (type)
        {
            case ArrayTypeSymbol array:
                var element = array.ElementType;
                var ranks = new StringBuilder(Ranks(array.Rank));
                while (element is ArrayTypeSymbol inner)
                {
                    ranks.Append(Ranks(inner.Rank));
                    element = inner.ElementType;
                }
                return TypeName(element) + ranks;
            case NullableTypeSymbol nullable:
                // A reference type's T? is the same C# type; the generated C# has nullable annotations off.
                return nullable.UnderlyingType.IsValueType ? TypeName(nullable.UnderlyingType) + "?" : TypeName(nullable.UnderlyingType);
            case NamedTypeSymbol named when SymbolDisplay.Keyword(named.SpecialType) is { } keyword:
                return keyword;
            case NamedTypeSymbol named:
                var outer = named.ContainingType is { } containing
                    ? TypeName(containing)
                    : named.ContainingNamespace is { IsGlobal: false } ns ? "global::" + string.Join(".", ns.FullName.Split('.').Select(Escape)) : "global:";
                var separator = named.ContainingType is null && named.ContainingNamespace is null or { IsGlobal: true } ? ":" : ".";
                var arguments = named.Arity > 0 ? $"<{string.Join(", ", named.TypeArguments.Select(TypeName))}>" : "";
                return $"{outer}{separator}{Escape(named.Name)}{arguments}";
            default:
                return Escape(type.Name);
        }
    }

    private static string Ranks(int rank) => $"[{new string(',', rank - 1)}]";

    /// <summary>A Nyxel name that is a C# keyword (<c>base</c>, <c>params</c>) is written with <c>@</c>.</summary>
    private static string Escape(string name) =>
        CSharpFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;
}
